//! 内置单线笔画字体（ASCII 为主）。
//!
//! 用途：在 `.gfont` 字库解密完成前，让排版 / 渲染 / G-code 全链路可运行、可测试。
//! 中文字形目前返回占位方框——真实笔迹由 `.gfont` 提供。

use super::{Glyph, InkMetrics, Stroke, StrokeFont};

const EM: f32 = 100.0;
const ADV: f32 = 62.0;

fn s(pts: &[(f32, f32)]) -> Stroke {
    Stroke::new(pts.iter().map(|&(x, y)| (x, y)).collect())
}

/// 七段数码管段坐标：0上 1左上 2右上 3中 4左下 5右下 6下
const SEG: [[(f32, f32); 2]; 7] = [
    [(12.0, 8.0), (48.0, 8.0)],
    [(12.0, 8.0), (12.0, 48.0)],
    [(48.0, 8.0), (48.0, 48.0)],
    [(12.0, 48.0), (48.0, 48.0)],
    [(12.0, 48.0), (12.0, 88.0)],
    [(48.0, 48.0), (48.0, 88.0)],
    [(12.0, 88.0), (48.0, 88.0)],
];

const DIGIT_SEGS: [&[usize]; 10] = [
    &[0, 1, 2, 4, 5, 6], // 0
    &[2, 5],             // 1
    &[0, 2, 3, 4, 6],    // 2
    &[0, 2, 3, 5, 6],    // 3
    &[1, 2, 3, 5],       // 4
    &[0, 1, 3, 5, 6],    // 5
    &[0, 1, 3, 4, 5, 6], // 6
    &[0, 2, 5],          // 7
    &[0, 1, 2, 3, 4, 5, 6], // 8
    &[0, 1, 2, 3, 5, 6], // 9
];

