/// 内置测试字体。
///
/// 坐标系：原点在 em 框**左上角**，x 向右、y 向下（字形墨迹 y ∈ [8,88]，em=100）。
#[derive(Debug, Default)]
pub struct BuiltinFont;

/// 内置字体的典型墨迹框（按 ASCII 全集统计一次并缓存）。
fn builtin_ink() -> InkMetrics {
    static CACHE: std::sync::OnceLock<InkMetrics> = std::sync::OnceLock::new();
    *CACHE.get_or_init(|| {
        let f = BuiltinFont;
        let glyphs: Vec<Glyph> = (0x20u8..0x7F)
            .filter_map(|b| f.glyph(b as char))
            .collect();
        super::ink_metrics(glyphs.iter())
    })
}

impl BuiltinFont {
    pub fn new() -> Self {
        BuiltinFont
    }
}

impl StrokeFont for BuiltinFont {
    fn name(&self) -> &str {
        "builtin-stroke"
    }
    fn em(&self) -> f32 {
        EM
    }
    fn glyph(&self, ch: char) -> Option<Glyph> {
        if ch == ' ' || ch == '\t' {
            return Some(Glyph::new(vec![], ADV * 0.6));
        }
        if ch.is_ascii_digit() {
            let d = ch.to_digit(10)? as usize;
            let strokes = DIGIT_SEGS[d].iter().map(|&i| s(&SEG[i])).collect();
            return Some(Glyph::new(strokes, ADV));
        }
        let up = ch.to_ascii_uppercase();
        if let Some(st) = letter(up) {
            return Some(Glyph::new(st, ADV));
        }
        // 未知字符（含中文）：占位方框，真实笔迹应由 .gfont 提供
        let tofu = vec![s(&[
            (14.0, 14.0), (46.0, 14.0), (46.0, 86.0), (14.0, 86.0), (14.0, 14.0),
        ])];
        Some(Glyph::new(tofu, ADV))
    }
    fn ink(&self) -> InkMetrics {
        builtin_ink()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ascii_glyphs_have_strokes() {
        let f = BuiltinFont::new();
        for c in "ABC123.-".chars() {
            let g = f.glyph(c).expect("glyph");
            assert!(!g.is_blank(), "blank for {}", c);
            assert!(g.advance > 0.0);
        }
    }

    #[test]
    fn space_is_blank() {
        let f = BuiltinFont::new();
        assert!(f.glyph(' ').unwrap().is_blank());
    }

    #[test]
    fn unknown_char_has_placeholder() {
        let f = BuiltinFont::new();
        let g = f.glyph('中').expect("placeholder");
        assert!(!g.is_blank());
    }
}
